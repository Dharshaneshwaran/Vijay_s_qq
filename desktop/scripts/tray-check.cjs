const { app, BrowserWindow } = require('electron');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..'), data = path.join(root, '.tools', `tray-check-${Date.now()}`);
fs.mkdirSync(data, { recursive: true }); app.setPath('userData', data);
const delay = ms => new Promise(r => setTimeout(r, ms));
const timeout = setTimeout(() => app.exit(1), 25000);
(async () => {
 await import(pathToFileURL(path.join(root, 'dist-electron/main.js')));
 await app.whenReady();
 await delay(1300);
 const windows = await import(pathToFileURL(path.join(root, 'dist-electron/windows.js')));
 const native = await import(pathToFileURL(path.join(root, 'dist-electron/tray.js')));
 const widget = windows.widget;
 assert.equal(native.tray.isDestroyed(), false);
 windows.dashboard.close();
 const position = widget.getPosition();
 native.tray.emit('click'); assert.equal(widget.isVisible(), false);
 await widget.webContents.executeJavaScript('window.qbit.addReminder({text:"Tray reminder",at:Date.now()+1200})');
 await delay(2400);
 const state = await widget.webContents.executeJavaScript('window.qbit.getState()');
 assert.equal(state.reminders[0].completed, true);
 assert.equal(widget.isVisible(), false);
 native.tray.emit('click'); assert.equal(widget.isVisible(), true);
 assert.deepEqual(widget.getPosition(), position);
 native.trayMenu.items.find(i => i.label === 'Pause animations').click();
 assert.equal((await widget.webContents.executeJavaScript('window.qbit.getState()')).settings.animationsPaused, true);
 widget.close(); assert.equal(widget.isDestroyed(), false); assert.equal(widget.isVisible(), false);
 assert.equal(BrowserWindow.getAllWindows().length, 1);
 console.log('PASS: native tray exists; left-click toggles same window at previous position; reminders continue while hidden; pause persists; window close hides without quitting.');
 clearTimeout(timeout); app.quit();
})().catch(e => { console.error(e); clearTimeout(timeout); app.exit(1); });
