const { app, BrowserWindow, powerMonitor } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const userData = path.join(root, '.tools', `smoke-${Date.now()}`);
fs.mkdirSync(userData, { recursive: true });
app.setPath('userData', userData);

const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const timeout = setTimeout(() => { console.error('FAIL: smoke check timed out'); app.exit(1); }, 90000);
async function waitFor(fn) { for (let i = 0; i < 600; i++) { const value = await fn(); if (value) return value; await delay(50); } throw new Error('Timed out waiting for application'); }
(async () => {
 const system = await import(pathToFileURL(path.join(root, 'dist-electron/system.js')).href);
 const si = require('systeminformation');
 const originalBattery = si.battery;
 const sampleBattery = { hasBattery: true, percent: 72, isCharging: false, acConnected: false, timeRemaining: 125 };
 assert.deepEqual(system.normalizeBattery(sampleBattery), { percent: 72, isCharging: false, acConnected: false, timeRemaining: 125 });
 assert.equal(system.normalizeBattery({ ...sampleBattery, hasBattery: false }), null);
 assert.equal(system.normalizeBattery({ ...sampleBattery, percent: -1 }), null);
 assert.equal(system.normalizeBattery({ ...sampleBattery, percent: NaN }), null);
 assert.equal(system.normalizeBattery({ ...sampleBattery, timeRemaining: -1 }).timeRemaining, null);
 assert.equal(system.normalizeBattery({ ...sampleBattery, isCharging: true, acConnected: true }).timeRemaining, null);
 let batteryReads = 0, batteryUpdates = 0;
 si.battery = async () => { batteryReads++; return sampleBattery; };
 const stopPolling = system.monitorBattery(() => batteryUpdates++);
 await waitFor(() => batteryUpdates === 1);
 assert.equal(system.systemStats().battery.percent, 72);
 await delay(10100);
 assert.equal(batteryReads, 2, 'battery refreshed at ten-second interval');
 stopPolling();
 si.battery = async () => { throw new Error('Telemetry unavailable'); };
 const stopFailure = system.monitorBattery(() => batteryUpdates++);
 await waitFor(() => batteryUpdates === 3);
 assert.equal(system.systemStats().battery, null, 'failed battery query clears stale values');
 stopFailure();
 si.battery = originalBattery;
 console.log('PASS: battery values, absent/invalid hardware, unavailable estimate, failed query and ten-second polling.');
 await import(pathToFileURL(path.join(root, 'dist-electron/main.js')).href);
 await app.whenReady();
 await waitFor(() => BrowserWindow.getAllWindows().length === 2);
 const widget = BrowserWindow.getAllWindows().find(w => !w.isResizable());
 let dashboard = BrowserWindow.getAllWindows().find(w => w.isResizable());
 for (const win of [widget, dashboard]) {
   await waitFor(async () => !win.webContents.isLoading() && await win.webContents.executeJavaScript('!!window.qbit && !!document.querySelector("button")'));
 }
 const evaluate = code => widget.webContents.executeJavaScript(code);
 await dashboard.webContents.executeJavaScript('Array.from(document.querySelectorAll("nav button")).find(b => b.textContent === "System").click()');
 dashboard.webContents.send('stats', { ...system.systemStats(), battery: sampleBattery });
 await waitFor(() => dashboard.webContents.executeJavaScript('document.querySelector(".stat-grid").textContent.includes("72%") && document.querySelector(".stat-grid").textContent.includes("2h 5m remaining")'));
 dashboard.webContents.send('stats', { ...system.systemStats(), battery: null });
 await waitFor(() => dashboard.webContents.executeJavaScript('document.querySelector(".stat-grid").textContent.includes("Battery unavailable")'));
 await dashboard.webContents.executeJavaScript('document.querySelector("nav button").click()');
 console.log('PASS: battery telemetry crosses the existing IPC bridge and renders values/unavailable state.');
 const preferences = widget.webContents.getLastWebPreferences();
 assert.equal(preferences.nodeIntegration, false);
 assert.equal(preferences.contextIsolation, true);
 assert.equal(preferences.sandbox, true);
 assert.equal(widget.isMinimizable(), true);
 assert.equal(widget.isMovable(), true);
 assert.equal(await evaluate('getComputedStyle(document.querySelector(".drag-handle")).getPropertyValue("-webkit-app-region")'), 'drag');
 assert.equal(await evaluate('getComputedStyle(document.querySelector(".face")).getPropertyValue("-webkit-app-region")'), 'no-drag');
 assert.equal(await evaluate('getComputedStyle(document.querySelector(".widget-minimize")).getPropertyValue("-webkit-app-region")'), 'no-drag');
 const beforeMove = widget.getPosition();
 const requested = [beforeMove[0] - 75, beforeMove[1] - 60];
 widget.setPosition(...requested);
 const moved = widget.getPosition();
 assert.ok(moved.every((n, i) => Math.abs(n - requested[i]) <= 1), 'native movement allows Windows DPI rounding');
 const windows = await import(pathToFileURL(path.join(root, 'dist-electron/windows.js')).href);
 assert.deepEqual(windows.widgetContextMenu().items.map(i => i.label), ['Open Control Center', 'Minimize QBIT', 'Quit QBIT']);
 console.log('PASS: drag/no-drag regions, native window movement, context menu and renderer isolation.');
 assert.equal((await evaluate('window.qbit.getState()')).reminders.length, 0);
 await evaluate('window.qbit.setSettings({ muted: true, volume: .2, expression: "sleepy", adaptiveExpressions: false })');
 assert.equal((await dashboard.webContents.executeJavaScript('window.qbit.getState()')).settings.muted, true);
 await waitFor(() => dashboard.webContents.executeJavaScript('!!document.querySelector(".face.sleepy")'));
 await evaluate('window.smokeEvents = 0; window.qbit.onReminder(() => window.smokeEvents++); window.qbit.onStats(s => window.smokeStats = s); true');
 const invalid = await evaluate('window.qbit.addReminder({ text: "", at: 0 }).then(() => false, () => true)');
 assert.equal(invalid, true, 'invalid reminder is rejected');
 await evaluate('window.qbit.addReminder({ text: "Smoke test reminder", at: Date.now() + 2000 })');
 dashboard.close();
 widget.removeAllListeners('show');
 widget.show();
 await evaluate('document.querySelector(".widget-minimize").click()');
 await waitFor(() => widget.isMinimized());
 console.log('PASS: hover button minimizes the native widget.');
 await delay(3500);
 let state = await evaluate('window.qbit.getState()');
 assert.equal(state.reminders[0].completed, true, 'scheduler survives Control Center close');
 assert.equal(await evaluate('window.smokeEvents'), 1, 'reminder fires once');
 assert.equal(widget.isMinimized(), true, 'reminders continue without restoring the widget');
 widget.restore();
 await waitFor(() => !widget.isMinimized());
 assert.deepEqual(widget.getPosition(), moved, 'restore retains the previous position');
 assert.equal(widget.isAlwaysOnTop(), true);
 widget.hide();
 console.log('PASS: reminder while minimized, restore, previous desktop position and always-on-top.');
 assert.equal(await evaluate('!!document.querySelector(".face.alert")'), true, 'alert expression survives state broadcast');
 await waitFor(async () => { const s=await evaluate('window.smokeStats'); return s && typeof s.cpu === 'number' && s.total>0; });
 const stats = await evaluate('window.smokeStats');
 assert.ok(stats && stats.cpu >= 0 && stats.cpu <= 100 && stats.total > 0, 'sampled system metrics');
 const { store } = await import(pathToFileURL(path.join(root, 'dist-electron/store.js')).href);
 store.set('reminders', [...store.get('reminders'), { id: 'resume-test', text: 'Overdue after sleep', at: Date.now() - 1000, completed: false }]);
 powerMonitor.emit('resume');
 await delay(100);
 assert.equal((await evaluate('window.qbit.getState()')).reminders.find(r => r.id === 'resume-test').completed, true);
 powerMonitor.emit('resume');
 await delay(100);
 assert.equal(await evaluate('window.smokeEvents'), 2, 'resume does not duplicate completed reminders');
 await evaluate('window.qbit.openDashboard()');
 await waitFor(() => BrowserWindow.getAllWindows().length === 2);
 dashboard = BrowserWindow.getAllWindows().find(w => w.isResizable());
 await waitFor(async () => !dashboard.webContents.isLoading() && await dashboard.webContents.executeJavaScript('!!document.querySelector(".shell")'));
 await evaluate('window.qbit.deleteReminder("resume-test")');
 state = await evaluate('window.qbit.getState()');
 const saved = JSON.parse(fs.readFileSync(path.join(userData, 'config.json'), 'utf8'));
 assert.equal(saved.settings.muted, true, 'settings persisted');
 assert.equal(saved.reminders.length, 1, 'deletion persisted');
 assert.equal(state.reminders.length, 1);
 console.log('PASS: two windows, IPC, input validation, settings sync, persistence, scheduler with dashboard closed, resume, no duplicate delivery, alert expression, system metrics, deletion and reopening.');
 clearTimeout(timeout); app.quit();
})().catch(error => { console.error(error); clearTimeout(timeout); app.exit(1); });



